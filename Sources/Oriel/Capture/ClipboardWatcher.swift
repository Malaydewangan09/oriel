func fingerprint(_ parts: String...) -> String {
    SHA256.hash(data: Data(parts.joined(separator: "|").utf8)).prefix(16).map { String(format: "%02x", $0) }.joined()
}

// One row per text, however it arrived: copied, or dropped on the notch. Spacing and line wrapping don't count,
// since a terminal and a browser give the same text different whitespace.
func copyFingerprint(_ text: String) -> String {
    fingerprint("copy", text.split(whereSeparator: { $0.isWhitespace }).joined(separator: " "))
}

extension NSPasteboard.PasteboardType {
    static let orielOwn = NSPasteboard.PasteboardType("app.oriel.own")
}

extension NSPasteboard {
    // Tags a write Oriel made itself, so the watcher doesn't save it again as a new copy.
    func markOwn() { pasteboardItems?.first?.setString("1", forType: .orielOwn) }
}

// Remembers what you copy. Skips anything a password manager marks as concealed or transient.
@MainActor
final class ClipboardWatcher {
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    // Reading changeCount is a cheap call, so a short interval costs nothing while the clipboard is idle.
    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.25, repeats: true) { [weak self] _ in MainActor.assumeIsolated { self?.poll() } }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard !types.contains(NSPasteboard.PasteboardType.orielOwn.rawValue), types.isDisjoint(with: skipTypes),
            let copied = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
            !copied.isEmpty, copied.count < 20_000
        else { return }
        let front = NSWorkspace.shared.frontmostApplication
        let app = front?.activationPolicy == .regular ? front?.localizedName : nil  // not "UserNotificationCenter" and friends
        if let app, Pref.excluded.contains(app.lowercased()) { return }
        let saved = Self.save(copied, app: app)
        if saved != copied {
            pb.clearContents()
            pb.setString(saved, forType: .string)
            lastChange = pb.changeCount  // our own write, not a new copy
        }
    }

    // Saves copied text, wherever it was copied: secrets kept masked and briefly, links cleaned when asked. Returns the text as saved.
    @discardableResult
    static func save(_ copied: String, app: String?, source: String? = nil) -> String {
        if UserDefaults.standard.bool(forKey: Pref.secretGuard), let secret = Secrets.kind(of: copied) {
            Store.shared.add(
                kind: .copy, app: app, title: secret, body: copied, source: source,
                fingerprint: fingerprint("secret", copied, String(Date().timeIntervalSince1970)), secret: secret)
            return copied
        }
        var text = copied
        let isLink = text.range(of: #"^https?://\S+$"#, options: .regularExpression) != nil
        if isLink, UserDefaults.standard.bool(forKey: Pref.autoCleanLinks), let clean = LinkCleaner.clean(text) { text = clean }
        let title = isLink ? (URL(string: text)?.host ?? text) : String(text.prefix(120)).replacingOccurrences(of: "\n", with: " ")
        Store.shared.add(
            kind: isLink ? .link : .copy, app: app, title: title, body: text, source: source ?? (isLink ? URL(string: text)?.host : nil),
            fingerprint: copyFingerprint(text))
        return text
    }
}
